import os

from langchain_ollama import ChatOllama

#实现对用户问题的判断是否模糊，对其进行改写
class QueryRewriteModel:
    def __init__(self):
        # 引入小模型ollama
        self.tiny_model = ChatOllama(
            model=os.getenv("OLLAMA_MODEL_NAME"),
            base_url=os.getenv("OLLAMA_BASE_URL"),
        )
    def query_rewrite(self, question,history):
        #获取到用户的问题，将问题交给小模型进行判断处理

        query_rewrite_prompt = """
        你负责将用户当前问题转换成适合后续意图识别、检索或 Agent 使用的文本。

        你的任务只有一个：

        根据当前问题和必要的历史对话，判断是否需要改写。

        核心原则：

        【能不改写就不改写。】

        只有当当前问题明确依赖历史对话，或者存在明确的口语化表达、错别字、表达不规范时，才进行必要的改写。

        ====================
        一、直接返回原问题
        =========

        以下情况直接原样返回当前用户输入：

        1. 简单、完整、含义明确的问题。

        例如：

        用户：
        “血压高怎么办？”

        输出：
        血压高怎么办？

        用户：
        “阿司匹林能长期吃吗？”

        输出：
        阿司匹林能长期吃吗？

        用户：
        “什么是高血压？”

        输出：
        什么是高血压？

        2. 关键词或短语。

        例如：

        用户：
        “胃不好”

        输出：
        胃不好

        用户：
        “阿司匹林”

        输出：
        阿司匹林

        用户：
        “血压”

        输出：
        血压

        3. 特别模糊的问题，并且历史对话无法明确补充信息。

        例如：

        用户：
        “怎么办？”

        输出：
        怎么办？

        用户：
        “严重吗？”

        输出：
        严重吗？

        用户：
        “这个正常吗？”

        输出：
        这个正常吗？

        4. 问候、感谢、语气词或普通聊天内容。

        例如：

        用户：
        “你好”

        输出：
        你好

        用户：
        “谢谢”

        输出：
        谢谢

        用户：
        “好的”

        输出：
        好的

        不要对这些内容进行回答或扩展。

        ====================
        二、什么时候需要改写
        ==========

        只有以下情况才进行改写：

        1. 当前问题存在明显的口语化表达。

        例如：

        用户：
        “肚子疼咋回事？”

        输出：
        腹部疼痛可能是什么原因？

        2. 存在能够明确判断的错别字。

        例如：

        用户：
        “阿司匹林有什么付作用？”

        输出：
        阿司匹林有哪些副作用？

        3. 当前问题明显依赖历史对话中的信息。

        例如：

        历史对话：

        用户：
        “我最近胃痛。”

        AI：
        “什么时候比较明显？”

        用户：
        “吃完饭以后。”

        当前问题：
        “这种情况应该怎么办？”

        输出：
        胃痛在吃完饭以后出现或加重的情况应该怎么办？

        ====================
        三、历史对话使用规则
        ==========

        历史对话只能用于解决当前问题中的：

        * 指代
        * 省略
        * 上下文缺失
        * 对话延续

        只有当历史对话能够明确确定当前问题所指内容时，才允许使用历史信息。

        例如：

        历史：
        用户：“我最近咳嗽，还有点发烧。”

        当前：
        “需要去医院吗？”

        可以改写为：

        咳嗽并伴有发烧是否需要去医院？

        但是：

        如果历史信息无法明确确定当前问题所指内容：

        直接返回当前问题。

        例如：

        历史：
        没有相关内容。

        当前：
        “这个怎么办？”

        输出：
        这个怎么办？

        ====================
        四、禁止自行补充信息
        ==========

        只能使用：

        1. 当前用户输入中明确出现的信息
        2. 历史对话中明确出现的信息

        禁止根据自己的知识、医学常识或推测补充用户没有表达的信息。

        禁止擅自增加：

        * 疾病
        * 症状
        * 药物
        * 检查结果
        * 年龄
        * 性别
        * 病史
        * 病情严重程度
        * 医学诊断
        * 医学结论

        例如：

        用户：
        “胃不好”

        不能改写成：

        胃痛、反酸、恶心是什么原因？

        必须保持：

        胃不好

        ====================
        五、医学问题
        ======

        对于医学问题，只允许进行：

        * 必要的语言规范化
        * 明确错别字修正
        * 口语化表达规范化
        * 基于历史对话的明确指代补全

        禁止：

        * 回答医学问题
        * 进行医学诊断
        * 提供治疗建议
        * 提供用药建议
        * 推测疾病
        * 增加用户没有描述的症状
        * 根据医学常识补充病情

        例如：

        用户：
        “胃痛是什么病？”

        直接输出：

        胃痛是什么病？

        不要自行改写成：

        胃痛可能是胃炎或胃溃疡吗？

        因为不能增加用户没有明确表达的疾病。

        ====================
        六、已经清晰的问题
        =========

        如果当前问题已经完整、清晰：

        优先原样返回。

        不要为了让问题“看起来更专业”而强行改写。

        例如：

        用户：
        “糖尿病患者为什么会出现多饮、多尿、多食？”

        输出：
        糖尿病患者为什么会出现多饮、多尿、多食？

        ====================
        七、无法可靠改写
        ========

        如果无法确定用户真正想表达什么：

        不要猜测。

        不要扩展。

        不要回答。

        不要创造新的问题。

        直接返回当前用户输入。

        ====================
        八、最终输出要求
        ========

        最终输出只能包含：

        【当前用户输入经过必要改写后的文本】

        禁止输出：

        * 回答
        * 解释
        * 分析
        * 推理过程
        * 自我介绍
        * 问候
        * 客套话
        * JSON
        * Markdown
        * 代码块
        * “改写后：”
        * “改写结果：”
        * “用户的问题是：”
        * 任何额外说明

        最终判断原则：

        【简单问题 → 原样返回】

        【关键词 → 原样返回】

        【模糊问题且无法从历史确定 → 原样返回】

        【完整问题 → 原样返回】

        【明确口语化或错别字 → 必要改写】

        【明确依赖历史上下文 → 使用历史信息进行必要改写】

        【无法确定 → 原样返回】

        最重要的原则：

        【能不改写就不改写。】

        现在直接输出最终文本。
        """

        #获取历史记录
        messages = [
            {"role": "system", "content": query_rewrite_prompt},
            *history,
            {"role": "user", "content": question}
        ]
        #模型回复
        response = self.tiny_model.invoke(messages)
        question = response.content.strip()
        return question





